import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border border-border bg-white p-6 text-text-primary shadow-soft-xs",
      hoverable &&
        "transition-all duration-200 hover:-translate-y-1 hover:border-slate-300 hover:shadow-soft-md",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

