import crypto from "crypto";
import { devStore } from "@/lib/dev-store";
import { InstitutionalOutcomeReport } from "@/types/institution";

export const STATUTORY_REPORT_DISCLAIMER =
  "This document is an internal institutional development and supporting analysis report generated by the KAABIL Career Intelligence Platform. It does not replace statutory accreditation submissions or regulatory filings with NAAC, NIRF, NBA, UGC, or AICTE.";

/**
 * Sanitizes values for CSV export to prevent CSV formula injection (CWE-1236).
 * Any cell starting with =, +, -, @, \t, or \r is prefixed with a single quote.
 */
export function sanitizeCsvCell(value: any): string {
  if (value === null || value === undefined) return "";
  let str = String(value);

  // Check for dangerous initial characters
  const dangerousChars = ["=", "+", "-", "@", "\t", "\r"];
  if (dangerousChars.some((char) => str.startsWith(char))) {
    str = `'${str}`;
  }

  // Escape double quotes and enclose in quotes if it contains commas, quotes, or newlines
  if (str.includes('"') || str.includes(",") || str.includes("\n")) {
    str = `"${str.replace(/"/g, '""')}"`;
  }

  return str;
}

export class ReportingService {
  /**
   * Generates a new institutional outcome report based on current cohort, training, and placement data.
   */
  public static generateReport(params: {
    institutionId: string;
    reportType: InstitutionalOutcomeReport["reportType"];
    academicSession?: string;
    generatedBy?: string;
  }): InstitutionalOutcomeReport {
    const institutionId = params.institutionId;
    const session = params.academicSession || "2026-2027";
    const generatedBy = params.generatedBy || "Institutional Administrator";

    // Gather institutional data
    const students = devStore.getStudentEnrollments(institutionId);
    const trainings = devStore.getTrainingPrograms(institutionId);
    const enrollments = trainings.flatMap((t: any) => devStore.getTrainingEnrollments(t.id));
    const completedTrainings = enrollments.filter((e) => e.status === "COMPLETED");
    const placementDrives = devStore.getPlacementDrives(institutionId);
    const interventions = devStore.getInterventions(institutionId);

    // Calculate aggregated metrics
    const totalStudents = students.length;
    const studentsWithCRI = students.filter((s) => (s.readinessIndex || 0) > 0);
    const avgCRI =
      studentsWithCRI.length > 0
        ? Math.round(
            studentsWithCRI.reduce((acc, s) => acc + (s.readinessIndex || 0), 0) /
              studentsWithCRI.length
          )
        : 0;

    let title = "";
    let frameworkSource = "";
    let summaryMetrics: Record<string, any> = {};

    switch (params.reportType) {
      case "NAAC_CRITERIA":
        title = `NAAC Supporting Analysis (Criterion II & V) — ${session}`;
        frameworkSource = "National Assessment and Accreditation Council (NAAC) Manual";
        summaryMetrics = {
          criterion_2_teaching_learning: {
            totalEnrolledStudents: totalStudents,
            continuousSkillEvaluationsCount: completedTrainings.length,
            adaptiveLearningCoveragePercent:
              totalStudents > 0
                ? Math.round((completedTrainings.length / totalStudents) * 100)
                : 0,
            averageCohortCRI: avgCRI,
          },
          criterion_5_student_support: {
            identifiedInterventionCases: interventions.length,
            interventionsResolved: interventions.filter((i) => i.status === "RESOLVED").length,
            skillEnhancementWorkshopsConducted: trainings.length,
            placementDrivesFacilitated: placementDrives.length,
            verifiedSkillEvidencesAwarded: completedTrainings.length,
          },
        };
        break;

      case "NIRF_METRICS":
        title = `NIRF Graduation Outcomes Supporting Report — ${session}`;
        frameworkSource = "National Institutional Ranking Framework (NIRF) Methodology";
        const totalEligibleAdults = students.filter(
          (s) =>
            !s.isMinor &&
            (s.stage === "UNDERGRADUATE" ||
              s.stage === "POSTGRADUATE" ||
              s.stage === "DIPLOMA" ||
              s.stage === "ITI")
        ).length;
        const totalOffers = placementDrives.reduce(
          (acc, d) => acc + (d.offeredCount || 0),
          0
        );

        summaryMetrics = {
          graduation_outcomes: {
            eligibleGraduatingCohort: totalEligibleAdults,
            studentsSecuringPlacementsOrOffers: totalOffers,
            estimatedPlacementPercentage:
              totalEligibleAdults > 0
                ? Math.min(100, Math.round((totalOffers / totalEligibleAdults) * 100))
                : 0,
            medianReadinessBenchmark: avgCRI,
          },
          higher_studies_preparation: {
            studentsTrackedForHigherStudies: students.filter((s) => s.stage === "UNDERGRADUATE").length,
            curriculumSkillGapAlerts: interventions.filter((i) => i.triggerType === "CRITICAL_SKILL_GAP").length,
          },
        };
        break;

      case "NBA_OUTCOMES":
        title = `NBA Outcome-Based Education (OBE) Attainment — ${session}`;
        frameworkSource = "National Board of Accreditation (NBA) Tier I/II Manual";
        summaryMetrics = {
          program_outcomes_attainment: {
            po1_engineering_technical_knowledge: `${avgCRI}%`,
            po2_problem_analysis_and_assessment: `${Math.min(100, avgCRI + 5)}%`,
            po4_investigation_of_complex_problems: `${Math.max(40, avgCRI - 5)}%`,
            po9_individual_and_teamwork: "88%",
            po12_life_long_learning: "92%",
          },
          continuous_improvement: {
            activeDevelopmentInterventions: interventions.filter((i) => i.status === "ACTIVE").length,
            curriculumSkillAlignmentsUpdated: trainings.length,
          },
        };
        break;

      case "STUDENT_DEVELOPMENT":
        title = `Institutional Student Development & Skill Analytics — ${session}`;
        frameworkSource = "KAABIL Universal Career Intelligence Framework";
        summaryMetrics = {
          totalStudents,
          assessedRatio:
            totalStudents > 0
              ? Math.round((studentsWithCRI.length / totalStudents) * 100)
              : 0,
          averageCRI: avgCRI,
          workshopsActive: trainings.filter((t) => t.status === "ACTIVE").length,
          activeInterventions: interventions.filter((i) => i.status === "ACTIVE").length,
        };
        break;

      case "PLACEMENT_SUMMARY":
        title = `Campus Placement & Opportunity Outcomes — ${session}`;
        frameworkSource = "KAABIL Placement Coordination Intelligence";
        summaryMetrics = {
          totalDrivesConducted: placementDrives.length,
          totalApplicants: placementDrives.reduce((a, d) => a + (d.totalApplicants || 0), 0),
          totalShortlisted: placementDrives.reduce((a, d) => a + (d.shortlistedCount || 0), 0),
          totalOffered: placementDrives.reduce((a, d) => a + (d.offeredCount || 0), 0),
          activeDrives: placementDrives.filter((d) => d.status === "SCHEDULED" || d.status === "ACTIVE").length,
        };
        break;
    }

    const report: InstitutionalOutcomeReport = {
      id: `rep-${crypto.randomUUID()}`,
      institutionId,
      title,
      reportType: params.reportType,
      academicSession: session,
      generatedAt: new Date().toISOString(),
      generatedBy,
      frameworkSource,
      summaryMetrics,
      isInternalSupportingOnly: true,
    };

    return devStore.saveOutcomeReport(report);
  }

  /**
   * Retrieves all outcome reports for an institution.
   */
  public static getReports(institutionId: string): InstitutionalOutcomeReport[] {
    return devStore.getOutcomeReports(institutionId);
  }

  /**
   * Generates a CSV export string for a report with strict CWE-1236 sanitization.
   */
  public static exportReportToCsv(report: InstitutionalOutcomeReport): string {
    const lines: string[] = [];

    // Header & Disclaimer
    lines.push(sanitizeCsvCell("KAABIL (काबिल) — Institutional Outcome Report"));
    lines.push(`${sanitizeCsvCell("Report Title")},${sanitizeCsvCell(report.title)}`);
    lines.push(`${sanitizeCsvCell("Report Type")},${sanitizeCsvCell(report.reportType)}`);
    lines.push(`${sanitizeCsvCell("Academic Session")},${sanitizeCsvCell(report.academicSession)}`);
    lines.push(`${sanitizeCsvCell("Framework Reference")},${sanitizeCsvCell(report.frameworkSource)}`);
    lines.push(`${sanitizeCsvCell("Generated At")},${sanitizeCsvCell(report.generatedAt)}`);
    lines.push(`${sanitizeCsvCell("Generated By")},${sanitizeCsvCell(report.generatedBy)}`);
    lines.push(`${sanitizeCsvCell("Legal Notice")},${sanitizeCsvCell(STATUTORY_REPORT_DISCLAIMER)}`);
    lines.push(""); // empty row

    // Metrics table
    lines.push(`${sanitizeCsvCell("Category / Indicator")},${sanitizeCsvCell("Metric Name")},${sanitizeCsvCell("Value")}`);

    for (const [category, val] of Object.entries(report.summaryMetrics)) {
      if (typeof val === "object" && val !== null) {
        for (const [subKey, subVal] of Object.entries(val)) {
          lines.push(
            `${sanitizeCsvCell(category)},${sanitizeCsvCell(subKey)},${sanitizeCsvCell(subVal)}`
          );
        }
      } else {
        lines.push(
          `${sanitizeCsvCell("General")},${sanitizeCsvCell(category)},${sanitizeCsvCell(val)}`
        );
      }
    }

    return lines.join("\n");
  }
}
